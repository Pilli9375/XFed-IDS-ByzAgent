"""Bundle the paper sources into paper/overleaf.zip for upload to Overleaf.

Run from the repository root: python paper/make_overleaf_zip.py
In Overleaf, set main.tex as the main document for the full version (body + appendices);
compile main_conference.tex for the body-and-references version.
"""
import glob
import os
import zipfile

ROOT = os.path.dirname(os.path.abspath(__file__))
FILES = ["main.tex", "appendix.tex", "main_conference.tex", "refs.bib"]
FILES += [os.path.relpath(p, ROOT).replace("\\", "/") for p in glob.glob(os.path.join(ROOT, "figs", "*.pdf"))]
FILES += [os.path.relpath(p, ROOT).replace("\\", "/") for p in glob.glob(os.path.join(ROOT, "figs", "*.png"))]

NOTE = """XFed-IDS paper -- Overleaf bundle
main.tex             full version: conference body + references + appendices (needs appendix.tex)
main_conference.tex  conference version: body + references only (inputs main.tex)
refs.bib             verified bibliography (IEEEtran style)
figs/                figures generated by paper/figs/make_figs.py in the repository
Compiler: pdfLaTeX or XeLaTeX both work. Lines ending in "% src: <file>" record where each number came from.
"""

with zipfile.ZipFile(os.path.join(ROOT, "overleaf.zip"), "w", zipfile.ZIP_DEFLATED) as z:
    for f in FILES:
        z.write(os.path.join(ROOT, f), f)
    z.writestr("README_overleaf.txt", NOTE)
print("wrote overleaf.zip with", len(FILES) + 1, "files")
