// Copies the self-hosted font files into public/fonts and writes src/fonts.css.
// Source: the @fontsource/* devDependencies. Only the weights/styles the site uses,
// and only the unicode subsets its text needs. Run after changing fonts: npm run fonts
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const mods = path.join(root, 'node_modules', '@fontsource');
const outDir = path.join(root, 'public', 'fonts');
mkdirSync(outDir, { recursive: true });

// package -> subsets x [weight, style] actually used (see styles.css)
const FONTS = {
  'brygada-1918': { subsets: ['latin', 'latin-ext'], faces: [[400, 'normal'], [400, 'italic'], [500, 'normal']] }, // display; 500 = nav brand
  'schibsted-grotesk': { subsets: ['latin', 'latin-ext'], faces: [[400, 'normal'], [500, 'normal']] }, // body; 500 = buttons
  'atkinson-hyperlegible-mono': { subsets: ['latin', 'latin-ext'], faces: [[300, 'normal'], [400, 'normal']] }, // numbers; 300 = loader counter
  alegreya: { subsets: ['latin', 'latin-ext', 'greek'], faces: [[400, 'italic']] }, // margin notes (contain α)
};

const css = ['/* Generated by scripts/copy-fonts.mjs from @fontsource packages. Do not edit by hand. */'];
const licenses = [];
for (const [pkg, { subsets, faces }] of Object.entries(FONTS)) {
  const version = JSON.parse(readFileSync(path.join(mods, pkg, 'package.json'), 'utf8')).version;
  licenses.push(`==== @fontsource/${pkg} ${version} ====\n` + readFileSync(path.join(mods, pkg, 'LICENSE'), 'utf8').trim());
  for (const subset of subsets) {
    for (const [w, style] of faces) {
      // the per-weight sheet holds one @font-face per subset, each with its unicode-range
      const sheet = readFileSync(path.join(mods, pkg, `${w}${style === 'italic' ? '-italic' : ''}.css`), 'utf8');
      const file = `${pkg}-${subset}-${w}-${style}.woff2`;
      const block = sheet.split('@font-face').find((b) => b.includes(`/${file})`));
      if (!block) throw new Error(`${pkg}: no @font-face for ${file}`);
      copyFileSync(path.join(mods, pkg, 'files', file), path.join(outDir, file));
      const family = block.match(/font-family:\s*'([^']+)'/)[1];
      const range = block.match(/unicode-range:\s*([^;]+);/)[1];
      css.push(`@font-face {\n  font-family: '${family}';\n  font-style: ${style};\n  font-weight: ${w};\n  font-display: swap;\n  src: url(/fonts/${file}) format('woff2');\n  unicode-range: ${range};\n}`);
    }
  }
}
writeFileSync(path.join(root, 'src', 'fonts.css'), css.join('\n') + '\n');
writeFileSync(path.join(outDir, 'LICENSES.txt'), 'Fonts self-hosted from the Fontsource packages below (SIL Open Font License 1.1).\n\n' + licenses.join('\n\n') + '\n');
console.log(`wrote ${css.length - 1} @font-face rules and public/fonts/LICENSES.txt`);
